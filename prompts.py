def body_user(title, factsheet_text, richness, cta, has_exercise, celeb, heart):
    chapters = 4 if (has_exercise and richness != "thin") else 3
    per_chapter = 14 if chapters == 4 else 17
    lo = C.THIN_SOURCE_LINES_MIN if richness == "thin" else C.CONTENT_LINES_MIN
    note = THIN_NOTE.format(lo=lo) if richness == "thin" else NORMAL_NOTE
    return BODY_USER.format(
        title=title,
        factsheet=factsheet_text,
        lo=lo,
        hi=C.CONTENT_LINES_MAX,
        chapters=chapters,
        per_chapter=per_chapter,
        cta=cta,
        heart=heart,
        celeb=celeb,
        tags=C.HASHTAG_COUNT,
        richness_note=note,
    )
